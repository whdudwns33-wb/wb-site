'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const nav = require('./tab-scroll.js');
assert.deepEqual(nav.bounds(0, 500, 1200), {overflow:true,left:false,right:true});
assert.deepEqual(nav.bounds(350, 500, 1200), {overflow:true,left:true,right:true});
assert.deepEqual(nav.bounds(700, 500, 1200), {overflow:true,left:true,right:false});
assert.deepEqual(nav.bounds(0, 500, 300), {overflow:false,left:false,right:false});
assert.equal(nav.revealDelta({left:40,right:400},{left:300,right:470}),70);
assert.equal(nav.revealDelta({left:40,right:400},{left:10,right:100}),-30);
assert.equal(nav.revealDelta({left:40,right:400},{left:60,right:180}),0);
const html = fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
assert.match(html, /src="tab-scroll.js" defer/);
assert.match(html, /id="tabScrollLeft"[^>]*aria-controls="tabs"/);
assert.match(html, /id="tabScrollRight"[^>]*aria-controls="tabs"/);
assert.match(html, /scrollbar-width: auto/);
assert.doesNotMatch(html, /\.tabs[^\n]*scrollbar-width: none/);
console.log('task tab scroll: passed');
