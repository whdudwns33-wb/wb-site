import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { readFileSync } from 'node:fs';
import { managerSeed } from './task-manager-setup.mjs';
import { hashPassword } from './task-director.js';
const db=new DatabaseSync(':memory:');
db.exec(readFileSync(new URL('./schema.sql',import.meta.url),'utf8'));
const accounts=[{staffId:'synthetic-a',loginId:'wb가상관리자'}];
const sql=await managerSeed(accounts,'synthetic-initial');
assert.ok(!sql.includes('synthetic-initial'));db.exec(sql);
const row=db.prepare('SELECT * FROM task_manager_accounts').get();
assert.equal(row.login_id,'wb가상관리자');assert.equal(row.must_change,1);
assert.equal(row.password_hash,await hashPassword('synthetic-initial',row.salt));
db.exec(await managerSeed(accounts,'another-password'));
assert.equal(db.prepare('SELECT password_hash FROM task_manager_accounts').get().password_hash,row.password_hash);
await assert.rejects(managerSeed([...accounts,...accounts],'synthetic-initial'),/중복/);
await assert.rejects(managerSeed([{staffId:'id',loginId:"wbx'; DROP TABLE staff;--"}],'synthetic-initial'),/형식/);
await assert.rejects(managerSeed(accounts,''),/비밀번호/);
console.log('manager setup: Korean login ID, hashed initial password, no reset on rerun, duplicate/injection validation: passed');
