import assert from 'node:assert/strict';
import {preserveLessonHistory,assertLessonRecordsVisible,lessonOccursForHistory} from './lesson-history.js';
const old={id:'a',staffId:'t',studentId:'s',start:'2026-08-01',repeat:'days',scheduleSlots:[{days:[6],startTime:'10:00',endTime:'10:50',validFrom:'2026-08-01'}]};
const wanted={...old,start:'2026-10-25',scheduleSlots:[{days:[0],startTime:'11:00',endTime:'11:50',validFrom:'2026-08-01'}]};
assert.throws(()=>preserveLessonHistory(old,wanted),/변경 적용일/);
assert.throws(()=>preserveLessonHistory(old,wanted,'2026-02-30'),/변경 적용일/);
const next=preserveLessonHistory(old,wanted,'2026-10-25');
assert.equal(next.start,old.start);
assert.equal(next.scheduleSlots[0].validTo,'2026-10-24');
assert.equal(next.scheduleSlots[1].validFrom,'2026-10-25');
assert.equal(lessonOccursForHistory(next,'2026-10-24'),true);
assert.equal(lessonOccursForHistory(next,'2026-10-31'),false);
assert.equal(lessonOccursForHistory(next,'2026-11-01'),true);
const memo=[{k:'a|2026-10-24',data:{note:'기존 메모'}}];
assertLessonRecordsVisible(old,next,memo);
assert.throws(()=>assertLessonRecordsVisible(old,preserveLessonHistory(old,wanted,'2026-10-23'),memo),/2026-10-24/);
assert.throws(()=>assertLessonRecordsVisible(old,{...next,studentId:'other'},memo),/학생을 바꿀/);
const moved=preserveLessonHistory(old,{...old,staffId:'new',start:'2026-10-25'},'2026-10-25');
assert.deepEqual(moved.scheduleSlots,old.scheduleSlots);assert.equal(moved.start,old.start);
const again=preserveLessonHistory(next,{...next,scheduleSlots:[{days:[1],startTime:'12:00',endTime:'12:50'}]},'2026-11-02');
assert.equal(again.scheduleSlots[0].validTo,'2026-10-24');
assert.equal(again.scheduleSlots[1].validTo,'2026-11-01');
assert.equal(lessonOccursForHistory(again,'2026-10-24'),true);
console.log('lesson history preservation passed');
